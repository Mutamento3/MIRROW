"""Structured output helpers for the daily diary.

The diary is generated by one Flash request.  The model may return a plain
diary (old clients) or the structured contract introduced in 2026-08.  This
module deliberately keeps parsing independent from SQLite so malformed model
output can never turn a day with real messages into an empty diary.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


CONTRACT_FIELDS = ("subjective_diary", "factual_timeline", "unfinished_threads")


@dataclass
class DiaryStructuredResult:
    """Normalised diary output.

    ``status`` is ``ok`` only when all three contract fields have the expected
    shape.  ``partial`` preserves any useful subjective text but is not safe
    as the sole compact-history source; callers can therefore fall back to
    authoritative raw messages.
    """

    subjective_diary: str = ""
    factual_timeline: List[Dict[str, Any]] = field(default_factory=list)
    unfinished_threads: List[Dict[str, Any]] = field(default_factory=list)
    # Optional autobiographical projections from the same diary generation.
    # They are AI's source-backed experience of a scene, not a second factual
    # authority and not a replacement for the subjective diary itself.
    k_recollections: List[Dict[str, Any]] = field(default_factory=list)
    recollections_status: str = "missing"
    contract_version: str = "legacy"
    status: str = "fallback"
    raw_output: str = ""
    # An optional, separately validated decision. Invalid/missing data never
    # changes diary parse status or asks the caller to regenerate the diary.
    open_loop_updates: Any = None
    open_loop_status: str = "missing"

    @property
    def as_dict(self) -> Dict[str, Any]:
        return {
            "subjective_diary": self.subjective_diary,
            "factual_timeline": self.factual_timeline,
            "unfinished_threads": self.unfinished_threads,
            "k_recollections": self.k_recollections,
            "_recollections_status": self.recollections_status,
            "_contract_version": self.contract_version,
            "_parse_status": self.status,
        }


def _strip_markdown_fence(text: str) -> str:
    text = str(text or "").strip()
    if not text.startswith("```"):
        return text
    # Accept ```json, ```JSON and an optional trailing fence.
    text = re.sub(r"^```(?:json)?\s*", "", text, count=1, flags=re.IGNORECASE)
    text = re.sub(r"\s*```\s*$", "", text, count=1)
    return text.strip()


def _extract_json_object(text: str) -> Optional[Dict[str, Any]]:
    """Find the first decodable JSON object, tolerating surrounding prose."""
    text = _strip_markdown_fence(text)
    if not text:
        return None
    decoder = json.JSONDecoder()
    for match in re.finditer(r"\{", text):
        try:
            obj, _ = decoder.raw_decode(text[match.start():])
        except (ValueError, TypeError):
            continue
        if isinstance(obj, dict):
            return obj
    return None


def _as_source_ids(value: Any) -> List[str]:
    if isinstance(value, str):
        values = [value]
    elif isinstance(value, (list, tuple, set)):
        values = list(value)
    else:
        values = []
    return [str(item).strip() for item in values if str(item).strip()]


def _normalise_timeline(value: Any) -> tuple[List[Dict[str, Any]], bool]:
    if not isinstance(value, list):
        return [], False
    result: List[Dict[str, Any]] = []
    valid = True
    for item in value:
        if not isinstance(item, dict):
            valid = False
            continue
        # Keep only factual, display-safe fields.  ``source_message_ids`` is
        # the canonical name; aliases make migration from experimental output
        # harmless without accepting arbitrary model metadata.
        event = str(item.get("event", item.get("summary", item.get("fact", ""))) or "").strip()
        timestamp = str(item.get("time", item.get("timestamp", "")) or "").strip()
        source_ids = _as_source_ids(
            item.get("source_message_ids", item.get("source_ids", item.get("message_ids", [])))
        )
        if not event or not source_ids:
            valid = False
        clean: Dict[str, Any] = {"time": timestamp, "event": event, "source_message_ids": source_ids}
        # Preserve a short type label if the model supplied one; no free-form
        # instructions or TODO semantics are persisted.
        kind = str(item.get("type", "") or "").strip()
        if kind:
            clean["type"] = kind[:40]
        result.append(clean)
    return result, valid


def _normalise_threads(value: Any) -> tuple[List[Dict[str, Any]], bool]:
    if not isinstance(value, list):
        return [], False
    result: List[Dict[str, Any]] = []
    valid = True
    for item in value:
        if isinstance(item, str):
            text = item.strip()
            if not text:
                valid = False
                continue
            result.append({"thread": text, "source_message_ids": []})
            continue
        if not isinstance(item, dict):
            valid = False
            continue
        text = str(item.get("thread", item.get("topic", item.get("summary", ""))) or "").strip()
        source_ids = _as_source_ids(
            item.get("source_message_ids", item.get("source_ids", item.get("message_ids", [])))
        )
        if not text:
            valid = False
            continue
        # This field is intentionally a continuity note only.  Do not persist
        # TODO/OB_Rev routing fields even if a model adds them.
        result.append({
            "thread": text,
            "source_message_ids": source_ids,
            **({"why_open": str(item.get("why_open"))[:240]} if item.get("why_open") else {}),
        })
    return result, valid


def _normalise_recollections(value: Any) -> tuple[List[Dict[str, Any]], bool]:
    """Normalise optional source-backed pieces of AI's lived recollection.

    This field was added after the three-field diary contract.  Missing it is
    therefore valid for historical rows; malformed supplied values are simply
    excluded from the read-side projection rather than invalidating an
    otherwise authoritative daily compact.
    """
    if value is None:
        return [], True
    if not isinstance(value, list):
        return [], False
    result: List[Dict[str, Any]] = []
    valid = True
    for item in value:
        if not isinstance(item, dict):
            valid = False
            continue
        memory = str(
            item.get("memory", item.get("recollection", item.get("experience", ""))) or ""
        ).strip()
        source_ids = _as_source_ids(
            item.get("source_message_ids", item.get("source_ids", item.get("message_ids", [])))
        )
        if not memory or not source_ids:
            valid = False
            continue
        result.append({"memory": memory, "source_message_ids": source_ids})
    return result, valid


def _fallback_subjective(text: str, parsed: Optional[Dict[str, Any]]) -> str:
    if isinstance(parsed, dict):
        value = parsed.get("subjective_diary")
        if isinstance(value, str) and value.strip():
            return value.strip()
    text = _strip_markdown_fence(text)
    # A truncated JSON response often still contains the subjective value.
    # Decode the JSON string rather than applying ``unicode_escape`` to
    # already decoded UTF-8 (the latter corrupts Chinese diary text).
    match = re.search(r'"subjective_diary"\s*:\s*', text)
    if match:
        try:
            value, _ = json.JSONDecoder().raw_decode(text[match.end():])
            if isinstance(value, str) and value.strip():
                return value.strip()
        except (ValueError, TypeError):
            pass
    match = re.search(r"'subjective_diary'\s*:\s*'([^']*)", text, re.S)
    if match:
        return match.group(1).strip()
    return text.strip().strip("\"'")


def parse_diary_output(raw_output: Any) -> DiaryStructuredResult:
    """Parse one Flash result without raising on malformed output."""
    direct_object = raw_output if isinstance(raw_output, dict) and any(
        field in raw_output for field in CONTRACT_FIELDS
    ) else None
    if isinstance(raw_output, dict):
        raw_text = str(raw_output.get("content") or raw_output.get("text") or "")
        if direct_object is not None and not raw_text:
            raw_text = json.dumps(raw_output, ensure_ascii=False)
    else:
        raw_text = str(raw_output or "")
    parsed = direct_object or _extract_json_object(raw_text)
    if parsed is None:
        subjective = _fallback_subjective(raw_text, None)
        return DiaryStructuredResult(subjective_diary=subjective, raw_output=raw_text, status="fallback")

    subjective = str(parsed.get("subjective_diary", "") or "").strip()
    timeline, timeline_ok = _normalise_timeline(parsed.get("factual_timeline"))
    threads, threads_ok = _normalise_threads(parsed.get("unfinished_threads"))
    recollections, recollections_ok = _normalise_recollections(parsed.get("k_recollections"))
    loop_updates = parsed.get("open_loop_updates")
    loop_status = ("missing" if "open_loop_updates" not in parsed else
                   "ok" if isinstance(loop_updates, list) else "invalid")
    contract_version = str(parsed.get("contract_version") or "legacy").strip()[:40]
    if "k_recollections" not in parsed:
        recollections_status = "missing"
    else:
        recollections_status = "ok" if recollections_ok else "partial"
    fields_ok = all(field in parsed for field in CONTRACT_FIELDS)
    status = "ok" if fields_ok and subjective and timeline_ok and threads_ok else "partial"
    if not subjective:
        subjective = _fallback_subjective(raw_text, parsed)
    return DiaryStructuredResult(
        subjective_diary=subjective,
        factual_timeline=timeline,
        unfinished_threads=threads,
        k_recollections=recollections,
        recollections_status=recollections_status,
        contract_version=contract_version,
        raw_output=raw_text,
        status=status,
        open_loop_updates=loop_updates,
        open_loop_status=loop_status,
    )


def structured_data_is_usable(value: Any) -> bool:
    """Whether structured data is safe as the compact proactive history."""
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except (TypeError, ValueError):
            return False
    if not isinstance(value, dict):
        return False
    if value.get("_parse_status") != "ok":
        return False
    timeline, timeline_ok = _normalise_timeline(value.get("factual_timeline"))
    threads, threads_ok = _normalise_threads(value.get("unfinished_threads"))
    # Structured diaries are generated only for days with real messages.  An
    # empty factual timeline therefore cannot replace yesterday's raw source;
    # it must fall back until a later diary regeneration succeeds.
    return (
        bool(str(value.get("subjective_diary", "") or "").strip())
        and bool(timeline)
        and timeline_ok
        and threads_ok
    )


__all__ = ["DiaryStructuredResult", "parse_diary_output", "structured_data_is_usable"]
