def turn_brief(job, writing):
    """The latest message supplements, rather than replaces, the original goal."""
    text = f"[工单原始需求；历史来源，后续变更见当前方案与补充]\n{job['brief']}"
    if job['plan']:
        text += f"\n[当前方案 v{job['plan_version']}；确认版本 {job['confirmed_version']}]\n{job['plan']}"
    text += '\n[本轮待处理补充；来源以正文和房间记录为准]\n' + (job['pending_text'] or '无新补充')
    return text + ('\n按已确认方案制作并实际交付。' if writing else '\n处理本轮需求差异，形成待 AI 确认的方案或提出真正阻塞的问题。')
